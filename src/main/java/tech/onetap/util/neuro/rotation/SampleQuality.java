package tech.onetap.util.neuro.rotation;

/**
 * Флаг качества сэмпла. Первоначальное обучение использует преимущественно CLEAN.
 */
public enum SampleQuality {
    /** Валидный сэмпл, цель видна, поворот осмысленный. */
    CLEAN,
    /** Переходное состояние (разгон/торможение прицела). */
    TRANSITION,
    /** Сэмпл на границе смены цели. */
    TARGET_SWITCH,
    /** Цель перекрыта блоками. */
    OCCLUDED,
    /** Невалидные данные, в обучение не идёт. */
    INVALID
}
